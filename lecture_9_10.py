import numpy as np

dist_values = np.linspace(0.3, 4, 40)  # 40 distances from 0.3 to 4 km

basket_values = np.linspace(1, 12, 40)  # 40 basket sizes from 1 to 12 items

D, B = np.meshgrid(dist_values, basket_values)

print("Number of what-if cases:", D.size)

"""LINEAR REGRESSION"""

# Import Linear Regression
from sklearn.linear_model import LinearRegression

# Create a simple regression model
formula = LinearRegression().fit(
    df[["Distance_KM", "Basket_Size"]],
    df["Delivery_Time_Min"]
)

# Display the impact of each variable
print("Each extra km adds about",
      round(formula.coef_[0], 2), "minutes")

print("Each extra item adds about",
      round(formula.coef_[1], 2), "minutes")

# Fill every what-if case with the expected delivery time

cases = pd.DataFrame({
    "Distance_KM": D.ravel(),
    "Basket_Size": B.ravel()
})

T = formula.predict(cases).reshape(D.shape)

print("Predicted delivery time table shape:", T.shape)

# Create contour plot
plt.contourf(D, B, T, levels=10, cmap="Purples")

# Add colour bar
plt.colorbar(label="Expected delivery time (minutes)")

# Add contour lines
lines = plt.contour(
    D, B, T,
    levels=[8, 10, 12, 15],
    colors="red"
)

# Add labels to contour lines
plt.clabel(lines, fmt="%d min")

# Add title and axis labels
plt.title("Distance and Basket Size That Keep the 10-Minute Promise")
plt.xlabel("Distance from store (km)")
plt.ylabel("Basket size (items)")

